package com.mx.curso.primitivos;

public class TestPuntoFlotante {


    public static void main(String[] args) {


        /**
         * para calculos aritmeticos, numeros reales
         */

        System.out.println("Primitivos de tipos de datos flotantes");


        float realFloat = 2.12e4f;
        System.out.println(realFloat);

        /**
         * Positivo a la izquierda, negativo a la derecha
         */

        float realFloat2 = 0.0000000015f;
        System.out.println(realFloat2);

        System.out.println("****************************");

        float realFloat3 = 1.5e-10f;
        System.out.println(realFloat3);
    }
}
